// 自由入力チャット向け: キーワードから該当する定型手続きを検索
// ★ 複数の候補のキーワードが同時にマッチする場合、最も長い（＝より具体的な）ものを優先する
// （route.tsの緊急ワード・トピック判定と同じ考え方）
export function findProceduralAnswer(query: string): ProceduralAnswer | null {
  let best: ProceduralAnswer | null = null;
  let bestLen = 0;
  for (const candidate of PROCEDURAL_ANSWERS) {
    for (const kw of candidate.keywords) {
      if (kw.length > bestLen && query.includes(kw)) {
        best = candidate;
        bestLen = kw.length;
      }
    }
  }
  return best;
}
